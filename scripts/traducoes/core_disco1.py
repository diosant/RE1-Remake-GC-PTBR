# Nomes dos locais na tela de salvar/carregar: cada letra vem seguida de
# {000B}{0000}{0020} (ou {0021} depois de espaco) e o fim tem {000B}{0000}{0022}.
def local(texto, prefixo='{0000}{0018}{0000}', fim='{000B}{0000}{0022}'):
    s = prefixo
    for c in texto:
        s += c + ('{000B}{0000}{0021}' if c == ' ' else '{000B}{0000}{0020}')
    return s + fim

